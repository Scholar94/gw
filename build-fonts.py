#!/usr/bin/env python3
"""Self-hosts the site's typefaces from the open-source (SIL OFL) @fontsource-variable packages.
Writes font-*.woff2 + fonts.css + LICENSE-fonts.txt next to this script. Run:  npm install && python3 build-fonts.py
Subsets: latin, latin-ext (+ vietnamese for Cormorant). Variable fonts: one file covers every weight."""
import re, shutil, pathlib
ROOT = pathlib.Path(__file__).resolve().parent
NM = ROOT / 'node_modules'
FAMILIES = [('Jost', 'jost', '@fontsource-variable/jost'),
            ('Cormorant Garamond', 'cormorant', '@fontsource-variable/cormorant-garamond'),
            ('Cinzel', 'cinzel', '@fontsource-variable/cinzel')]
KEEP = ('latin', 'latin-ext', 'vietnamese')
blocks, licenses = [], []
for css_name, slug, pkg in FAMILIES:
    for sheet in ('index.css', 'wght-italic.css'):
        path = NM / pkg / sheet
        if not path.exists(): continue
        css = path.read_text(encoding='utf-8')
        for m in re.finditer(r'/\*\s*([\w-]+)\s*\*/\s*(@font-face\s*\{.*?\})', css, re.S):
            tag, block = m.group(1), m.group(2)
            sub = re.search(r'-(latin-ext|latin|vietnamese|cyrillic-ext|cyrillic|greek-ext|greek)-wght', tag)
            if not sub or sub.group(1) not in KEEP: continue
            src = re.search(r'url\(\./files/([^)]+\.woff2)\)', block).group(1)
            italic = 'italic' in src
            out = f'font-{slug}-{sub.group(1)}{"-italic" if italic else ""}.woff2'
            shutil.copy(NM / pkg / 'files' / src, ROOT / out)
            block = re.sub(r"font-family:[^;]+;", f"font-family: '{css_name}';", block)
            block = re.sub(r"src:[^;]*;", f"src: url('{out}') format('woff2-variations');", block)
            blocks.append(block)
    lic = NM / pkg / 'LICENSE'
    if lic.exists(): licenses.append(f'===== {css_name} ({pkg}) =====\n' + lic.read_text(encoding='utf-8').strip())
(ROOT / 'fonts.css').write_text('/* Self-hosted variable fonts (SIL Open Font License; see LICENSE-fonts.txt). Generated by build-fonts.py. */\n' + '\n'.join(blocks) + '\n', encoding='utf-8')
(ROOT / 'LICENSE-fonts.txt').write_text('\n\n'.join(licenses) + '\n', encoding='utf-8')
print(f'{len(blocks)} font faces written; licences: {len(licenses)}')
